function flagEmoji(code: string): string {
  const offset = 0x1f1e6 - 65;
  return [...code.toUpperCase()]
    .map((c) => String.fromCodePoint(c.charCodeAt(0) + offset))
    .join("");
}

// Keys sorted longest-first so contains matching prefers more specific entries
const SORTED_KEYS = Object.keys(COUNTRY_CODES).sort((a, b) => b.length - a.length);

// Matches purely numeric / postal-code tokens like "860-8601" or "10001"
const POSTAL_RE = /^[\d][\d\s\-]+$/;

export function getCountryFlags(countriesStr: string, countryCodes?: string): string {
  // If we have stored ISO codes, use them directly — no map needed
  if (countryCodes && countryCodes.trim()) {
    const seen = new Set<string>();
    return countryCodes
      .split(",")
      .map(c => c.trim().toUpperCase())
      .filter(c => c.length === 2 && !seen.has(c) && seen.add(c))
      .slice(0, 4)
      .map(code => flagEmoji(code))
      .join(" ");
  }

  // Fallback: parse from the display_name string (existing logic)
  if (!countriesStr) return "";

  const seen = new Set<string>();
  const flags: string[] = [];

  const parts = countriesStr
    .split(/[,，、\/]/)
    .map((s) => s.trim())
    .filter(Boolean);

  for (const name of parts) {
    if (flags.length >= 4) break;

    // skip postal codes
    if (POSTAL_RE.test(name)) continue;

    const lower = name.toLowerCase();
    let code: string | undefined;

    // 1. exact match
    code = COUNTRY_CODES[name] ?? COUNTRY_CODES[lower];

    // 2. Japanese administrative suffix (県/都/道/府) → JP
    if (!code && /[都道府県]/.test(name)) code = "JP";

    // 3. Korean administrative patterns → KR
    if (!code && /특별시|광역시|대한민국|특별자치/.test(name)) code = "KR";

    // 4. contains fallback
    if (!code) {
      for (const key of SORTED_KEYS) {
        if (lower.includes(key.toLowerCase())) {
          code = COUNTRY_CODES[key];
          break;
        }
      }
    }

    if (code && !seen.has(code)) {
      seen.add(code);
      flags.push(flagEmoji(code));
    }
  }

  return flags.join(" ");
}

